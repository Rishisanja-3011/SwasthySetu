"""Mechanically rename a project label in versioned text and module paths.

Pass --apply after reviewing the dry-run counts. Binary assets must be
regenerated by their own generators; ignored private/runtime files are excluded.
"""

import argparse
from pathlib import Path
import re
import subprocess


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("old")
    parser.add_argument("new")
    parser.add_argument("--alias", action="append", default=[])
    parser.add_argument("--apply", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    pattern = re.compile("|".join(re.escape(name) for name in [args.old, *args.alias]), re.I)

    def replacement(match):
        value = match.group()
        return args.new.upper() if value.isupper() else args.new.lower() if value.islower() else args.new

    def rename(value):
        return pattern.sub(replacement, value)

    tracked = subprocess.check_output(
        ["git", "ls-files", "--cached", "--others", "--exclude-standard", "-z"], cwd=root,
    ).decode().split("\0")
    edits = []
    paths = set()
    for name in sorted(set(tracked)):
        path = root / name
        if not path.is_file() or path.is_symlink():
            continue
        for part in [path, *path.parents]:
            if part == root:
                break
            if pattern.search(part.name):
                paths.add(part)
        data = path.read_bytes()
        if b"\0" in data or path.suffix.lower() in {".pdf", ".png", ".jpg", ".jpeg", ".webp", ".ico", ".zip"}:
            continue
        try:
            text = data.decode("utf-8")
        except UnicodeDecodeError:
            continue
        updated = rename(text)
        if updated != text:
            edits.append((path, data, updated.encode("utf-8")))

    moves = sorted(paths, key=lambda path: len(path.parts), reverse=True)
    for path in moves:
        target = path.with_name(rename(path.name))
        if target.exists():
            raise RuntimeError(f"Rename target already exists: {target.relative_to(root)}")
    print(f"Text files to update: {len(edits)}; files/directories to rename: {len(moves)}")
    if not args.apply:
        return
    for path, original, updated in edits:
        if path.read_bytes() != original:
            raise RuntimeError(f"File changed during rename: {path.relative_to(root)}")
        path.write_bytes(updated)
    for path in moves:
        path.rename(path.with_name(rename(path.name)))
    print("Rename complete; original text encodings and line endings preserved.")


if __name__ == "__main__":
    main()
